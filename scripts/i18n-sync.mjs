#!/usr/bin/env node
/**
 * Regenerate everything derived from the language registry
 * (src/lib/i18n/languages.ts):
 *
 *   1. Generated regional overlays: for every registry entry with an overlay
 *      transform ("swiss-german", "british-english"), src/messages/<tag>.json =
 *      transform(base catalog) + hand-maintained terms in
 *      src/messages/overlays/<tag>.terms.json. Only changed keys are written.
 *      Hand-written overlays (transform "none", e.g. fr-CH) are left alone.
 *   2. src/messages/index.ts: one import per catalog, complete catalogs
 *      type-checked against en.json.
 *
 *   npm run i18n:sync            # write
 *   npm run i18n:sync -- --check # exit 1 when something is out of date (CI)
 */
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { join, relative } from "node:path";
import {
  CATALOG_LANGUAGES,
  MESSAGES_DIR,
  ROOT,
  buildOverlay,
  catalogPath,
  readJson,
  stringifyCatalog,
  termsPath,
} from "./lib/i18n.mjs";

const CHECK = process.argv.includes("--check");
const stale = [];

function emit(file, content) {
  const current = existsSync(file) ? readFileSync(file, "utf8") : null;
  if (current === content) return;
  if (CHECK) stale.push(relative(ROOT, file));
  else {
    writeFileSync(file, content);
    console.log(`wrote ${relative(ROOT, file)}`);
  }
}

// 1. Generated overlays -------------------------------------------------------
export function generatedOverlay(entry) {
  const base = readJson(catalogPath(entry.overlay.base));
  const terms = readJson(termsPath(entry.tag), {});
  return buildOverlay(base, entry.overlay.transform, terms);
}

for (const entry of CATALOG_LANGUAGES) {
  if (!entry.overlay || entry.overlay.transform === "none") continue;
  emit(catalogPath(entry.tag), stringifyCatalog(generatedOverlay(entry)));
}

// 2. Catalog index --------------------------------------------------------------
const ident = (tag) => `m_${tag.replace(/[^A-Za-z0-9]/g, "_")}`;
const lines = [
  "// Generated by scripts/i18n-sync.mjs from src/lib/i18n/languages.ts. Do not edit:",
  "// add the catalog file + registry entry, then run `npm run i18n:sync`.",
  'import type { Messages, PartialMessages } from "@/lib/i18n/translator";',
  ...CATALOG_LANGUAGES.map((l) => `import ${ident(l.tag)} from "./${l.tag}.json";`),
  "",
  "/** Complete catalogs are type-checked against en.json: a missing key fails `tsc`. */",
  "const complete = (m: Messages): PartialMessages => m;",
  "/** Partial catalogs and regional overlays: any subset of the English keys. */",
  "const partial = (m: unknown): PartialMessages => m as PartialMessages;",
  "",
  "export const CATALOG_SOURCES: Record<string, PartialMessages> = {",
  ...CATALOG_LANGUAGES.map((l) => {
    const kind = l.status === "complete" && !l.overlay ? "complete" : "partial";
    return `  ${JSON.stringify(l.tag)}: ${kind}(${ident(l.tag)}),`;
  }),
  "};",
  "",
];
for (const l of CATALOG_LANGUAGES) {
  if (!existsSync(catalogPath(l.tag))) {
    console.error(`✖ registry lists "${l.tag}" (status ${l.status}) but src/messages/${l.tag}.json is missing`);
    process.exit(1);
  }
}
emit(join(MESSAGES_DIR, "index.ts"), lines.join("\n"));

if (CHECK) {
  if (stale.length) {
    console.error(`✖ out of date (run \`npm run i18n:sync\`): ${stale.join(", ")}`);
    process.exit(1);
  }
  console.log("✔ overlays and src/messages/index.ts are in sync with the registry");
}
